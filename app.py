"""Streamlit UI for the WhatsApp chat analyzer.

This file only draws the page. Parsing lives in whatsapp_analyzer/parser.py
and the numbers come from whatsapp_analyzer/analysis.py.

Run it with:  streamlit run app.py
"""

from __future__ import annotations

from pathlib import Path

import altair as alt
import pandas as pd
import streamlit as st

from whatsapp_analyzer import analysis
from whatsapp_analyzer.parser import ANDROID, DAY_FIRST, MONTH_FIRST, YEAR_FIRST, load_export, parse_chat
from whatsapp_analyzer.text import parse_custom_stopwords

EXAMPLES = Path(__file__).parent / "examples"
SAMPLES = {
    "Android style": EXAMPLES / "sample_chat_android.txt",
    "iPhone style": EXAMPLES / "sample_chat_iphone.txt",
}
EVERYONE = "Everyone"
DATE_ORDERS = {"Detect automatically": "auto", "Day first (25/12)": DAY_FIRST, "Month first (12/25)": MONTH_FIRST}
ORDER_NAMES = {DAY_FIRST: "day-first dates", MONTH_FIRST: "month-first dates", YEAR_FIRST: "year-first dates"}

PRIVACY_NOTE = (
    "**Your chat stays on this computer.** The file is read into memory, analysed here "
    "and never uploaded, logged or saved to disk."
)

# Chart colours: one blue for every single-series chart, and a light-to-dark
# ramp of the same blue for the heatmap. Cells with no messages are grey.
BLUE = "#2a78d6"
BLUE_RAMP = ["#cde2fb", "#86b6ef", "#3987e5", "#1c5cab", "#0d366b"]
EMPTY_CELL = "#f0efec"

st.set_page_config(page_title="WhatsApp Chat Analyzer", page_icon=":speech_balloon:", layout="wide")


@st.cache_data(show_spinner=False, max_entries=2)
def parse(data: bytes, filename: str, date_order: str) -> tuple[pd.DataFrame, dict]:
    """Parse the uploaded bytes. The cache lives in this process's memory only."""
    result = parse_chat(load_export(data, filename), date_order)
    info = {
        "style": result.style,
        "date_order": result.date_order,
        "ambiguous": result.date_order_ambiguous,
        "clock": result.clock,
        "unparsed_lines": result.unparsed_lines,
        "parsed": len(result.messages),
    }
    return result.to_dataframe(), info


def sidebar_source() -> tuple[bytes, str, bool] | None:
    """Ask for a chat. Returns (bytes, file name, is_sample) or None."""
    st.sidebar.header("Chat")
    st.sidebar.info(PRIVACY_NOTE)
    upload = st.sidebar.file_uploader(
        "Exported chat (.txt, or the .zip from iPhone)",
        type=["txt", "zip"],
        help="In WhatsApp: open the chat, then More, then Export chat, then Without media.",
    )
    use_sample = st.sidebar.toggle(
        "Use the synthetic sample chat",
        key="use_sample",
        disabled=upload is not None,
        help="A made-up group chat generated by a script. No real people, no real messages.",
    )
    if upload is not None:
        return upload.getvalue(), upload.name, False
    if use_sample:
        style = st.sidebar.radio("Sample export style", list(SAMPLES), horizontal=True, key="sample_style")
        path = SAMPLES[style]
        return path.read_bytes(), path.name, True
    return None


def welcome() -> None:
    st.info(PRIVACY_NOTE)
    st.markdown(
        """
        **To start**, upload an exported chat in the sidebar, or switch on
        *Use the synthetic sample chat* to see the app with made-up data.

        **How to export a chat from WhatsApp**

        1. Open the chat or group.
        2. Android: tap the three dots, then **More**, then **Export chat**.
           iPhone: tap the chat name at the top, scroll down, then **Export chat**.
        3. Choose **Without media**.
        4. Save the file to this computer and upload it here. Android gives a `.txt`
           file, iPhone gives a `.zip`. Both work.
        """
    )


def describe_format(info: dict, is_sample: bool) -> None:
    phone = "Android" if info["style"] == ANDROID else "iPhone"
    parts = [
        f"{phone} export",
        ORDER_NAMES[info["date_order"]],
        f"{info['clock'][:2]}-hour clock",
        f"{info['parsed']:,} entries read",
        f"{info['unparsed_lines']:,} lines skipped",
    ]
    if is_sample:
        st.warning("You are looking at the **synthetic sample chat**. Every name and message in it is invented.")
    st.caption("Detected: " + " · ".join(parts))
    if info["ambiguous"]:
        st.warning(
            "No date in this file shows whether the day or the month comes first, so "
            f"**{ORDER_NAMES[info['date_order']]}** is a guess. If the dates look wrong, "
            "set the date order under Options in the sidebar."
        )


def show_overall(df: pd.DataFrame) -> None:
    stats = analysis.overall_stats(df)
    tiles = st.columns(6)
    tiles[0].metric("Messages", f"{stats['messages']:,}")
    tiles[1].metric("Words", f"{stats['words']:,}")
    tiles[2].metric("Media", f"{stats['media']:,}")
    tiles[3].metric("Links", f"{stats['links']:,}")
    tiles[4].metric("People", f"{stats['people']:,}")
    tiles[5].metric("Active days", f"{stats['active_days']:,}")
    if stats["messages"]:
        st.caption(
            f"From {stats['first_message']:%d %b %Y} to {stats['last_message']:%d %b %Y}. "
            f"Messages are text plus media. {stats['deleted']:,} deleted-message placeholders "
            "and all system notices are left out."
        )


def show_table(table: pd.DataFrame, label: str = "Show the numbers") -> None:
    with st.expander(label):
        st.dataframe(table, hide_index=True)


def ranked_bars(table: pd.DataFrame, label: str, value: str, value_title: str, label_size: int = 12) -> alt.Chart:
    """Horizontal bars in the order of the table, each with its number at the end."""
    base = alt.Chart(table).encode(
        y=alt.Y(f"{label}:N", sort=None, title=None, axis=alt.Axis(labelFontSize=label_size, labelLimit=240)),
        x=alt.X(f"{value}:Q", title=value_title, axis=alt.Axis(tickMinStep=1, tickCount=6)),
        tooltip=[alt.Tooltip(f"{label}:N"), alt.Tooltip(f"{value}:Q", title=value_title, format=",")],
    )
    bars = base.mark_bar(color=BLUE, cornerRadiusEnd=4)
    numbers = base.mark_text(align="left", dx=5, fontSize=12).encode(text=alt.Text(f"{value}:Q", format=","))
    return (bars + numbers).properties(height=max(120, 28 * len(table) + 40))


def column_bars(table: pd.DataFrame, x: alt.X, tooltip_field: str, tooltip_title: str) -> alt.Chart:
    return (
        alt.Chart(table)
        .mark_bar(color=BLUE, cornerRadiusEnd=4)
        .encode(
            x=x,
            y=alt.Y("messages:Q", title="Messages", axis=alt.Axis(tickMinStep=1)),
            tooltip=[alt.Tooltip(tooltip_field, title=tooltip_title), alt.Tooltip("messages:Q", title="Messages", format=",")],
        )
        .properties(height=280)
    )


def per_day_chart(table: pd.DataFrame) -> alt.Chart:
    nearest = alt.selection_point(nearest=True, on="pointerover", fields=["date"], empty=False)
    base = alt.Chart(table).encode(
        x=alt.X("date:T", title=None),
        y=alt.Y("messages:Q", title="Messages", axis=alt.Axis(tickMinStep=1)),
    )
    line = base.mark_line(color=BLUE, strokeWidth=2)
    hover = (
        base.mark_point(color=BLUE, filled=True, size=70)
        .encode(
            opacity=alt.condition(nearest, alt.value(1), alt.value(0)),
            tooltip=[
                alt.Tooltip("date:T", title="Day", format="%a %d %b %Y"),
                alt.Tooltip("messages:Q", title="Messages", format=","),
            ],
        )
        .add_params(nearest)
    )
    return (line + hover).properties(height=280)


def heatmap_chart(table: pd.DataFrame) -> alt.Chart:
    return (
        alt.Chart(table)
        .mark_rect(stroke="white", strokeWidth=2, cornerRadius=3)
        .encode(
            x=alt.X("hour:O", title="Hour of day", axis=alt.Axis(labelAngle=0)),
            y=alt.Y("weekday:O", sort=analysis.WEEKDAYS, title=None),
            color=alt.condition(
                alt.datum.messages > 0,
                alt.Color("messages:Q", scale=alt.Scale(range=BLUE_RAMP), legend=alt.Legend(title="Messages")),
                alt.value(EMPTY_CELL),
            ),
            tooltip=[
                alt.Tooltip("weekday:O", title="Day"),
                alt.Tooltip("hour:O", title="Hour"),
                alt.Tooltip("messages:Q", title="Messages", format=","),
            ],
        )
        .properties(height=300)
    )


def show_activity(df: pd.DataFrame) -> None:
    per_day = analysis.messages_per_day(df)
    st.markdown("**Messages per day**")
    st.altair_chart(per_day_chart(per_day), width="stretch")
    show_table(per_day.assign(date=per_day["date"].dt.date))

    left, right = st.columns(2)
    with left:
        per_hour = analysis.messages_per_hour(df)
        st.markdown("**Messages by hour of day**")
        hours = alt.X("hour:O", title="Hour of day", axis=alt.Axis(labelAngle=0))
        st.altair_chart(column_bars(per_hour, hours, "hour:O", "Hour"), width="stretch")
        show_table(per_hour)
    with right:
        per_weekday = analysis.messages_per_weekday(df)
        st.markdown("**Messages by weekday**")
        days = alt.X("weekday:O", sort=analysis.WEEKDAYS, title=None, axis=alt.Axis(labelAngle=0))
        st.altair_chart(column_bars(per_weekday, days, "weekday:O", "Day"), width="stretch")
        show_table(per_weekday)

    heatmap = analysis.weekday_hour_heatmap(df)
    st.markdown("**When the chat is busiest: weekday by hour**")
    st.altair_chart(heatmap_chart(heatmap), width="stretch")
    st.caption("Darker means more messages. Grey cells have none. Times are as written in the export.")
    wide = heatmap.pivot(index="weekday", columns="hour", values="messages").reindex(analysis.WEEKDAYS)
    with st.expander("Show the numbers"):
        st.dataframe(wide)


def show_people(df: pd.DataFrame, filtered: bool) -> None:
    table = analysis.per_person_stats(df)
    if filtered:
        st.caption("This comparison always shows the whole chat, whatever is picked in the sidebar.")
    st.markdown("**Most active people**")
    st.altair_chart(ranked_bars(table, "person", "messages", "Messages"), width="stretch")
    st.markdown("**Per person**")
    st.dataframe(
        table,
        hide_index=True,
        column_config={
            "person": "Person",
            "messages": st.column_config.NumberColumn("Messages", format="localized"),
            "share_pct": st.column_config.NumberColumn("Share of messages", format="%.1f%%"),
            "words": st.column_config.NumberColumn("Words", format="localized"),
            "avg_words": st.column_config.NumberColumn("Words per message", format="%.1f"),
            "avg_chars": st.column_config.NumberColumn("Characters per message", format="%.1f"),
            "media": "Media",
            "links": "Links",
        },
    )
    st.caption("Words and characters per message are averages over text messages, media left out.")


def word_cloud_image(frequencies: dict[str, int]):
    """Draw the word cloud, or return None when the wordcloud package is missing."""
    try:
        from wordcloud import WordCloud
    except ImportError:
        return None
    shades = BLUE_RAMP[2:]

    def blue(word, font_size, position, orientation, random_state, **_):
        return shades[random_state.randint(0, len(shades) - 1)]

    cloud = WordCloud(width=1400, height=560, background_color="white", color_func=blue, random_state=7, max_words=120)
    return cloud.generate_from_frequencies(frequencies).to_image()


def show_words(df: pd.DataFrame, top_n: int, custom_stopwords: set[str], want_cloud: bool) -> None:
    words = analysis.top_words(df, top_n, custom_stopwords)
    emojis = analysis.top_emojis(df, top_n)
    left, right = st.columns(2)
    with left:
        st.markdown(f"**Top {len(words)} words**")
        if words.empty:
            st.write("No words to count.")
        else:
            st.altair_chart(ranked_bars(words, "word", "count", "Times used"), width="stretch")
            show_table(words)
    with right:
        st.markdown(f"**Top {len(emojis)} emojis**")
        if emojis.empty:
            st.write("No emojis found.")
        else:
            st.altair_chart(ranked_bars(emojis, "emoji", "count", "Times used", label_size=18), width="stretch")
            show_table(emojis)
    ignored = f" and {len(custom_stopwords)} of your own" if custom_stopwords else ""
    st.caption(
        f"Common English words (the, and, is, ...){ignored} are left out. Links, numbers and media "
        "placeholders are not counted as words. Add your own words to ignore under Options in the sidebar."
    )

    if want_cloud and not words.empty:
        st.markdown("**Word cloud**")
        image = word_cloud_image(analysis.word_frequencies(df, custom_stopwords))
        if image is None:
            st.info("The word cloud needs the `wordcloud` package: `pip install wordcloud`.")
        else:
            st.image(image, width="stretch")
            st.caption("Bigger words are used more often. The built-in font only draws Latin letters.")


def main() -> None:
    st.title("WhatsApp Chat Analyzer")
    st.caption("Statistics for an exported WhatsApp chat, worked out on your own machine.")

    source = sidebar_source()
    if source is None:
        welcome()
        return
    data, filename, is_sample = source

    person_slot = st.sidebar.container()
    with st.sidebar.expander("Options"):
        date_order = DATE_ORDERS[st.selectbox("Date order", list(DATE_ORDERS), key="date_order")]
        top_n = st.slider("How many top words and emojis", 5, 40, 15, key="top_n")
        custom_stopwords = parse_custom_stopwords(
            st.text_area(
                "Extra words to ignore",
                key="custom_stopwords",
                placeholder="haha, ok, yeah",
                help="Separate words with commas, spaces or new lines.",
            )
        )
        want_cloud = st.checkbox("Show a word cloud", key="word_cloud")

    try:
        df, info = parse(data, filename, date_order)
    except ValueError as error:
        st.error(str(error))
        return
    if not analysis.people(df):
        st.error(
            "No WhatsApp messages were recognised in this file. It needs to be a chat exported "
            "with WhatsApp's own Export chat option. Export formats differ between phone "
            "languages and regions, and this app reads the English ones."
        )
        return

    person = person_slot.selectbox(
        "Show", [EVERYONE] + analysis.people(df), key="person", help="The whole chat or one person."
    )
    view = analysis.filter_sender(df, None if person == EVERYONE else person)

    describe_format(info, is_sample)
    st.subheader("Whole chat" if person == EVERYONE else f"Only {person}")
    show_overall(view)

    activity_tab, people_tab, words_tab = st.tabs(["Activity", "People", "Words and emojis"])
    with activity_tab:
        show_activity(view)
    with people_tab:
        show_people(df, filtered=person != EVERYONE)
    with words_tab:
        show_words(view, top_n, custom_stopwords, want_cloud)


main()
