"""Streamlit UI for the WhatsApp chat analyzer.

This file only draws the page. Parsing lives in whatsapp_analyzer/parser.py
and the numbers come from whatsapp_analyzer/analysis.py.

Run it with:  streamlit run app.py
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
import streamlit as st

from whatsapp_analyzer import analysis
from whatsapp_analyzer.parser import ANDROID, DAY_FIRST, MONTH_FIRST, YEAR_FIRST, load_export, parse_chat

EXAMPLES = Path(__file__).parent / "examples"
SAMPLES = {
    "Android style": EXAMPLES / "sample_chat_android.txt",
    "iPhone style": EXAMPLES / "sample_chat_iphone.txt",
}
EVERYONE = "Everyone"
DATE_ORDERS = {"Detect automatically": "auto", "Day first (25/12)": DAY_FIRST, "Month first (12/25)": MONTH_FIRST}
ORDER_NAMES = {DAY_FIRST: "day-first dates", MONTH_FIRST: "month-first dates", YEAR_FIRST: "year-first dates"}

PRIVACY_NOTE = (
    "**Your chat stays on this computer.** The file is read into memory, analysed here "
    "and never uploaded, logged or saved to disk."
)

st.set_page_config(page_title="WhatsApp Chat Analyzer", page_icon=":speech_balloon:", layout="wide")


@st.cache_data(show_spinner=False, max_entries=2)
def parse(data: bytes, filename: str, date_order: str) -> tuple[pd.DataFrame, dict]:
    """Parse the uploaded bytes. The cache lives in this process's memory only."""
    result = parse_chat(load_export(data, filename), date_order)
    info = {
        "style": result.style,
        "date_order": result.date_order,
        "ambiguous": result.date_order_ambiguous,
        "clock": result.clock,
        "unparsed_lines": result.unparsed_lines,
        "parsed": len(result.messages),
    }
    return result.to_dataframe(), info


def sidebar_source() -> tuple[bytes, str, bool] | None:
    """Ask for a chat. Returns (bytes, file name, is_sample) or None."""
    st.sidebar.header("Chat")
    st.sidebar.info(PRIVACY_NOTE)
    upload = st.sidebar.file_uploader(
        "Exported chat (.txt, or the .zip from iPhone)",
        type=["txt", "zip"],
        help="In WhatsApp: open the chat, then More, then Export chat, then Without media.",
    )
    use_sample = st.sidebar.toggle(
        "Use the synthetic sample chat",
        key="use_sample",
        disabled=upload is not None,
        help="A made-up group chat generated by a script. No real people, no real messages.",
    )
    if upload is not None:
        return upload.getvalue(), upload.name, False
    if use_sample:
        style = st.sidebar.radio("Sample export style", list(SAMPLES), horizontal=True, key="sample_style")
        path = SAMPLES[style]
        return path.read_bytes(), path.name, True
    return None


def welcome() -> None:
    st.info(PRIVACY_NOTE)
    st.markdown(
        """
        **To start**, upload an exported chat in the sidebar, or switch on
        *Use the synthetic sample chat* to see the app with made-up data.

        **How to export a chat from WhatsApp**

        1. Open the chat or group.
        2. Android: tap the three dots, then **More**, then **Export chat**.
           iPhone: tap the chat name at the top, scroll down, then **Export chat**.
        3. Choose **Without media**.
        4. Save the file to this computer and upload it here. Android gives a `.txt`
           file, iPhone gives a `.zip`. Both work.
        """
    )


def describe_format(info: dict, is_sample: bool) -> None:
    phone = "Android" if info["style"] == ANDROID else "iPhone"
    parts = [
        f"{phone} export",
        ORDER_NAMES[info["date_order"]],
        f"{info['clock'][:2]}-hour clock",
        f"{info['parsed']:,} entries read",
        f"{info['unparsed_lines']:,} lines skipped",
    ]
    if is_sample:
        st.warning("You are looking at the **synthetic sample chat**. Every name and message in it is invented.")
    st.caption("Detected: " + " · ".join(parts))
    if info["ambiguous"]:
        st.warning(
            "No date in this file shows whether the day or the month comes first, so "
            f"**{ORDER_NAMES[info['date_order']]}** is a guess. If the dates look wrong, "
            "set the date order under Options in the sidebar."
        )


def show_overall(df: pd.DataFrame) -> None:
    stats = analysis.overall_stats(df)
    tiles = st.columns(6)
    tiles[0].metric("Messages", f"{stats['messages']:,}")
    tiles[1].metric("Words", f"{stats['words']:,}")
    tiles[2].metric("Media", f"{stats['media']:,}")
    tiles[3].metric("Links", f"{stats['links']:,}")
    tiles[4].metric("People", f"{stats['people']:,}")
    tiles[5].metric("Active days", f"{stats['active_days']:,}")
    if stats["messages"]:
        st.caption(
            f"From {stats['first_message']:%d %b %Y} to {stats['last_message']:%d %b %Y}. "
            f"Messages are text plus media. {stats['deleted']:,} deleted-message placeholders "
            "and all system notices are left out."
        )


def main() -> None:
    st.title("WhatsApp Chat Analyzer")
    st.caption("Statistics for an exported WhatsApp chat, worked out on your own machine.")

    source = sidebar_source()
    if source is None:
        welcome()
        return
    data, filename, is_sample = source

    with st.sidebar.expander("Options"):
        date_order = DATE_ORDERS[st.selectbox("Date order", list(DATE_ORDERS), key="date_order")]

    try:
        df, info = parse(data, filename, date_order)
    except ValueError as error:
        st.error(str(error))
        return
    if not analysis.people(df):
        st.error(
            "No WhatsApp messages were recognised in this file. It needs to be a chat exported "
            "with WhatsApp's own Export chat option. Export formats differ between phone "
            "languages and regions, and this app reads the English ones."
        )
        return

    person = st.sidebar.selectbox(
        "Show", [EVERYONE] + analysis.people(df), key="person", help="The whole chat or one person."
    )
    view = analysis.filter_sender(df, None if person == EVERYONE else person)

    describe_format(info, is_sample)
    st.subheader("Whole chat" if person == EVERYONE else f"Only {person}")
    show_overall(view)


main()
